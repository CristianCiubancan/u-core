function patchLocale(filePath, additions) {
  const raw = fs.readFileSync(filePath, 'utf8');
  const json = JSON.parse(raw);
  json.ui = json.ui ?? {};
  for (const [k, v] of Object.entries(additions)) {
    json.ui[k] = v;
  }
  // 2-space indent + trailing newline matches the existing files.
  fs.writeFileSync(filePath, JSON.stringify(json, null, 2) + '\n', 'utf8');
}

const qbmDir = path.join(repo, 'src/plugins/[qb]/qb-multicharacter/translations');
const qbsDir = path.join(repo, 'src/plugins/[qb]/qb-spawn/translations');

let touched = 0;
for (const [lng, additions] of Object.entries(QBM_KEYS)) {
  const file = path.join(qbmDir, `${lng}.json`);
  if (!fs.existsSync(file)) {
    console.warn(`SKIP missing ${file}`);
    continue;
  }
  patchLocale(file, additions);
  touched++;
}
for (const [lng, additions] of Object.entries(QBS_KEYS)) {
  const file = path.join(qbsDir, `${lng}.json`);
  if (!fs.existsSync(file)) {
    console.warn(`SKIP missing ${file}`);
    continue;
  }
  patchLocale(file, additions);
  touched++;
}

console.log(`Patched ${touched} locale files.`);
